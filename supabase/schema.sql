create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  role text not null default 'user' check (role in ('user','admin'))
);
create table if not exists public.stadiums (
  id bigint generated by default as identity primary key,
  name text not null,
  city text,
  capacity integer check (capacity is null or capacity >= 0)
);
create table if not exists public.referees (
  id bigint generated by default as identity primary key,
  name text not null,
  country text
);
create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  name text not null,
  city text,
  coach text,
  stadium_id bigint references public.stadiums(id) on delete set null
);
create table if not exists public.players (
  id bigint generated by default as identity primary key,
  name text not null,
  pos text,
  number integer check (number is null or number between 0 and 99),
  team_id bigint references public.teams(id) on delete cascade
);
create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  home_id bigint not null references public.teams(id) on delete cascade,
  away_id bigint not null references public.teams(id) on delete cascade,
  date date not null,
  stadium_id bigint references public.stadiums(id) on delete set null,
  referee_id bigint references public.referees(id) on delete set null,
  hg integer not null default 0 check (hg >= 0),
  ag integer not null default 0 check (ag >= 0),
  played boolean not null default false,
  constraint matches_different_teams check (home_id <> away_id)
);
create table if not exists public.events (
  id bigint generated by default as identity primary key,
  match_id bigint references public.matches(id) on delete cascade,
  player_id bigint references public.players(id) on delete cascade,
  type text not null check (type in ('goal','yellow','red')),
  minute integer check (minute is null or minute between 0 and 130)
);
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  text text not null,
  date timestamptz not null default now()
);

create index if not exists players_team_id_idx on public.players(team_id);
create index if not exists matches_date_idx on public.matches(date);
create index if not exists matches_home_id_idx on public.matches(home_id);
create index if not exists matches_away_id_idx on public.matches(away_id);
create index if not exists events_match_id_idx on public.events(match_id);
create index if not exists events_player_id_idx on public.events(player_id);

